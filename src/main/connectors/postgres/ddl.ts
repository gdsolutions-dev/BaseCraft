// PostgreSQL text of a server migration (C7 R4–R8): plan entries → DDL and multi-row INSERTs. Pure: no import of `pg`.
// Every row value is a parameter; a literal Default Value is the only literal, written by pgLiteral.
import type { FieldProps } from '../../../shared/field-types';
import type { Literal, ServerForeignKey, ServerTable } from '../../migrate/plan';
import { pgIdent } from './sql-expr';
import { castOf } from './sql-query';

const NUMBERS: Record<string, string> = { byte: 'smallint', integer: 'smallint', longInteger: 'integer', single: 'real', double: 'double precision' };
const invalid = (): never => { throw new Error('bc:invalidArgument'); };

/** Defence in depth: a size, precision or scale is written into the type text, so it is an integer in range or nothing. */
const int = (v: number | undefined, def: number, min: number, max: number): number => {
  const n = v ?? def;
  return Number.isInteger(n) && n >= min && n <= max ? n : invalid();
};

/** R4: the column type of a BaseCraft field (Byte's CHECK is pgCreateTable's). */
export function pgColumnType(p: FieldProps): string {
  switch (p.type) {
    case 'autoNumber': return 'integer GENERATED BY DEFAULT AS IDENTITY';
    case 'shortText': return `varchar(${int(p.size, 255, 1, 255)})`;
    case 'number': return p.numberSize === 'decimal' ? `numeric(${int(p.precision, 18, 1, 28)},${int(p.scale, 0, 0, int(p.precision, 18, 1, 28))})` : NUMBERS[p.numberSize ?? 'longInteger'] ?? invalid();
    case 'currency': return 'numeric(19,4)';
    case 'dateTime': return 'timestamp(0)';
    case 'yesNo': return 'boolean';
    default: return 'text'; // Long Text, Hyperlink
  }
}

/** R5: a literal default as SQL. Text with a backslash goes as an E string (its meaning then never depends on
 *  standard_conforming_strings); a number or a date is checked to be one (a plan entry is never trusted as SQL). */
export function pgLiteral(l: Literal): string {
  switch (l.k) {
    case 'str': return l.v.includes('\\') ? `E'${l.v.replace(/\\/g, '\\\\').replace(/'/g, "''")}'` : `'${l.v.replace(/'/g, "''")}'`;
    case 'num': return /^-?\d+(\.\d+)?(e[+-]?\d+)?$/i.test(l.v) ? l.v : invalid();
    case 'date': return /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(l.v) ? `TIMESTAMP '${l.v}'` : invalid();
    case 'bool': return l.v ? 'true' : 'false';
  }
}

const tableSql = (t: { schema: string; name: string }) => `${pgIdent(t.schema)}.${pgIdent(t.name)}`;

/** R5: NOT NULL for Required, key and Yes/No fields; a literal default (Yes/No: false without one); PRIMARY KEY in design order. */
export function pgCreateTable(t: ServerTable): string {
  const cols = t.fields.map(({ name, props: p, default: d }) => {
    const c = pgIdent(name);
    const notNull = p.required || p.primaryKey || t.key.includes(name) || p.type === 'yesNo';
    const def = d ? pgLiteral(d) : p.type === 'yesNo' ? 'false' : undefined;
    return [c, pgColumnType(p), ...(p.type === 'number' && p.numberSize === 'byte' ? [`CHECK (${c} BETWEEN 0 AND 255)`] : []),
      ...(notNull ? ['NOT NULL'] : []), ...(def ? [`DEFAULT ${def}`] : [])].join(' ');
  });
  if (t.key.length) cols.push(`PRIMARY KEY (${t.key.map(pgIdent).join(', ')})`);
  return `CREATE TABLE ${tableSql(t)} (${cols.join(', ')})`;
}

/** R8: one INSERT of `rows` rows, each value `$n::cast` with the cast the connector's reads bind (castOf). */
export function pgInsertRows(t: ServerTable, rows: number): { sql: string; casts: string[] } {
  const casts = t.fields.map((x) => castOf({ name: x.name, type: x.props.type, props: x.props }));
  const tuples = Array.from({ length: rows }, (_, r) => `(${casts.map((c, i) => `$${r * casts.length + i + 1}::${c}`).join(', ')})`);
  return { sql: `INSERT INTO ${tableSql(t)} (${t.fields.map((x) => pgIdent(x.name)).join(', ')}) VALUES ${tuples.join(', ')}`, casts };
}

/** R8: the AutoNumber's identity restarted at nextId, then each index (named in the table's schema). */
export function pgFinishTable(t: ServerTable): string[] {
  const auto = t.fields.find((x) => x.props.type === 'autoNumber');
  return [
    ...(auto && t.nextId !== undefined ? [`ALTER TABLE ${tableSql(t)} ALTER COLUMN ${pgIdent(auto.name)} RESTART WITH ${Math.trunc(t.nextId)}`] : []),
    ...t.indexes.map((ix) => `CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${pgIdent(ix.name)} ON ${tableSql(t)} (${ix.fields.map((x) => `${pgIdent(x.name)}${x.desc ? ' DESC' : ''}`).join(', ')})`),
  ];
}

const ACTION = { cascade: 'CASCADE', noAction: 'NO ACTION' } as const;
/** R7: an enforced relation as a foreign key with its cascades. */
export function pgForeignKey(fk: ServerForeignKey): string {
  return `ALTER TABLE ${tableSql({ schema: fk.schema, name: fk.child })} ADD CONSTRAINT ${pgIdent(fk.name)} FOREIGN KEY (${fk.childFields.map(pgIdent).join(', ')}) `
    + `REFERENCES ${tableSql({ schema: fk.schema, name: fk.parent })} (${fk.parentFields.map(pgIdent).join(', ')}) ON DELETE ${ACTION[fk.onDelete]} ON UPDATE ${ACTION[fk.onUpdate]}`;
}
