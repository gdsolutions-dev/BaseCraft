import { expect, it } from 'vitest';
import { defaultProps, type FieldProps, type FieldType } from '../../../shared/field-types';
import type { Literal, ServerField, ServerForeignKey, ServerTable } from '../../migrate/plan';
import { pgColumnType, pgCreateTable, pgFinishTable, pgForeignKey, pgInsertRows, pgLiteral } from './ddl';

const props = (type: FieldType, o: Partial<FieldProps> = {}): FieldProps => ({ ...defaultProps(type), ...o });
const field = (name: string, type: FieldType, o: Partial<FieldProps> & { default?: Literal } = {}): ServerField => {
  const { default: d, ...p } = o;
  return { name, props: props(type, p), ...(d && { default: d }) };
};
const auto = (name: string) => field(name, 'autoNumber');
const short = (name: string, size: number, o: Partial<FieldProps> & { default?: Literal } = {}) => field(name, 'shortText', { size, ...o });
const byte = (name: string) => field(name, 'number', { numberSize: 'byte' });
const yesNo = (name: string) => field(name, 'yesNo');
const table = (name: string, fields: ServerField[], o: Partial<ServerTable> = {}): ServerTable =>
  ({ name, schema: 'public', fields, key: fields.filter((x) => x.props.primaryKey).map((x) => x.name), indexes: [], rows: 0, ...o });

it('R4: every BaseCraft type', () => {
  expect(pgColumnType(props('autoNumber'))).toBe('integer GENERATED BY DEFAULT AS IDENTITY');
  expect(pgColumnType(props('number', { numberSize: 'byte' }))).toBe('smallint'); // the CHECK is part of the column, below
  expect(pgColumnType(props('number', { numberSize: 'integer' }))).toBe('smallint');
  expect(pgColumnType(props('number'))).toBe('integer');
  expect(pgColumnType(props('number', { numberSize: 'single' }))).toBe('real');
  expect(pgColumnType(props('number', { numberSize: 'double' }))).toBe('double precision');
  expect(pgColumnType(props('currency'))).toBe('numeric(19,4)');
  expect(pgColumnType(props('number', { numberSize: 'decimal', precision: 28, scale: 10 }))).toBe('numeric(28,10)');
  expect(pgColumnType(props('dateTime'))).toBe('timestamp(0)');
  expect(pgColumnType(props('shortText', { size: 40 }))).toBe('varchar(40)');
  expect(pgColumnType(props('longText'))).toBe('text');
  expect(pgColumnType(props('hyperlink'))).toBe('text');
  expect(pgColumnType(props('yesNo'))).toBe('boolean');
});

it('literal defaults: quotes doubled, backslashes in an E string, non-Latin text as is; numbers, dates, Yes/No', () => {
  expect(pgLiteral({ k: 'str', v: "O'Brien" })).toBe("'O''Brien'");
  expect(pgLiteral({ k: 'str', v: 'C:\\x\'y' })).toBe("E'C:\\\\x''y'");
  expect(pgLiteral({ k: 'str', v: '東京 "été"' })).toBe('\'東京 "été"\'');
  expect(pgLiteral({ k: 'date', v: '2026-01-01 00:00:00' })).toBe("TIMESTAMP '2026-01-01 00:00:00'");
  expect(pgLiteral({ k: 'bool', v: true })).toBe('true');
  expect(pgLiteral({ k: 'num', v: '-2.5' })).toBe('-2.5');
  // never text a plan entry did not make: anything but a number or a date is refused
  expect(() => pgLiteral({ k: 'num', v: '1; DROP TABLE x' })).toThrow('bc:invalidArgument');
  expect(() => pgLiteral({ k: 'date', v: "2026-01-01' OR '" })).toThrow('bc:invalidArgument');
});

it('CREATE TABLE: quoted names, NOT NULL, defaults, Byte check, Yes/No, primary key', () => {
  expect(pgCreateTable(table('Cl"i', [auto('N°'), short('Nom', 40, { required: true, default: { k: 'str', v: "O'Brien" } }), byte('Qte'), yesNo('Ok')])))
    .toBe(`CREATE TABLE "public"."Cl""i" ("N°" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL, "Nom" varchar(40) NOT NULL DEFAULT 'O''Brien', `
      + `"Qte" smallint CHECK ("Qte" BETWEEN 0 AND 255), "Ok" boolean NOT NULL DEFAULT false, PRIMARY KEY ("N°"))`);
  // a composite key in design order, NOT NULL on each; a Yes/No literal default; no key: no PRIMARY KEY
  expect(pgCreateTable(table('L', [field('B', 'number', { primaryKey: true }), field('A', 'shortText', { size: 5, primaryKey: true }), field('Ok', 'yesNo', { default: { k: 'bool', v: true } })], { schema: 's' })))
    .toBe('CREATE TABLE "s"."L" ("B" integer NOT NULL, "A" varchar(5) NOT NULL, "Ok" boolean NOT NULL DEFAULT true, PRIMARY KEY ("B", "A"))');
  expect(pgCreateTable(table('K', [field('X', 'dateTime', { default: { k: 'date', v: '2026-01-02 03:04:05' } })]))).toBe('CREATE TABLE "public"."K" ("X" timestamp(0) DEFAULT TIMESTAMP \'2026-01-02 03:04:05\')');
});

it('a multi-row INSERT with one cast parameter per value', () => {
  // the casts are those the connector's insert binds (driver.ts line 174), shown here for int4 and text
  expect(pgInsertRows(table('T', [auto('N°'), short('Nom', 40)]), 2).sql).toBe('INSERT INTO "public"."T" ("N°", "Nom") VALUES ($1::int4, $2::text), ($3::int4, $4::text)');
  expect(pgInsertRows(table('T', [auto('N°'), field('M', 'currency'), field('D', 'number', { numberSize: 'double' }), field('Le', 'dateTime'), yesNo('Ok'), byte('B')]), 1).casts)
    .toEqual(['int4', 'numeric', 'float8', 'timestamp', 'boolean', 'int4']);
});

it('finish: the identity restarts at nextId, then the indexes', () => {
  const tt = table('T', [auto('N°'), short('Code', 5), short('A', 5), short('B', 5)], { nextId: 6, indexes: [
    { name: 'T_Code', fields: [{ name: 'Code', desc: false }], unique: true },
    { name: 'T_AB', fields: [{ name: 'A', desc: false }, { name: 'B', desc: true }], unique: false }] });
  expect(pgFinishTable(tt)).toEqual(['ALTER TABLE "public"."T" ALTER COLUMN "N°" RESTART WITH 6', 'CREATE UNIQUE INDEX "T_Code" ON "public"."T" ("Code")',
    'CREATE INDEX "T_AB" ON "public"."T" ("A", "B" DESC)']);
  expect(pgFinishTable(table('U', [short('Code', 5)]))).toEqual([]); // no AutoNumber, no index
});

it('foreign keys with their cascades', () => {
  const fk: ServerForeignKey = { name: 'ClientsCommandes', relation: 'ClientsCommandes', schema: 'public', child: 'Commandes', childFields: ['Client'],
    parent: 'Clients', parentFields: ['N°'], onDelete: 'cascade', onUpdate: 'noAction' };
  expect(pgForeignKey(fk)).toBe('ALTER TABLE "public"."Commandes" ADD CONSTRAINT "ClientsCommandes" FOREIGN KEY ("Client") REFERENCES "public"."Clients" ("N°") ON DELETE CASCADE ON UPDATE NO ACTION');
  expect(pgForeignKey({ ...fk, childFields: ['A', 'B'], parentFields: ['X', 'Y'], onDelete: 'noAction', onUpdate: 'cascade' }))
    .toBe('ALTER TABLE "public"."Commandes" ADD CONSTRAINT "ClientsCommandes" FOREIGN KEY ("A", "B") REFERENCES "public"."Clients" ("X", "Y") ON DELETE NO ACTION ON UPDATE CASCADE');
});

it('a size, precision or scale outside its integer range never reaches the type text', () => {
  for (const o of [{ size: '10); DROP TABLE x; --' }, { size: 0 }, { size: 256 }, { size: 1.5 }] as unknown as Partial<FieldProps>[])
    expect(() => pgColumnType(props('shortText', o))).toThrow('bc:invalidArgument');
  const dec = (precision: unknown, scale: unknown) => () => pgColumnType(props('number', { numberSize: 'decimal', precision, scale } as Partial<FieldProps>));
  expect(dec(2.5, 0)).toThrow('bc:invalidArgument');
  expect(dec(29, 0)).toThrow('bc:invalidArgument');
  expect(dec(5, 6)).toThrow('bc:invalidArgument');
  expect(dec(5, '1); DROP TABLE x; --')).toThrow('bc:invalidArgument');
  expect(dec(28, 28)()).toBe('numeric(28,28)');
});
