type Ctx = { admin: Client; schema: string; tables: RemoteTable[]; session: (o?: { timeout?: number }, metas?: Record<string, LinkMeta>) => Session };
/** The seeded schema linked into front-ends (one per session asked, as two workstations); every session closed after. */
async function live(fn: (x: Ctx) => Promise<void>): Promise<void> {
  const dir = fs.realpathSync.native(fs.mkdtempSync(join(os.tmpdir(), 'bcpg-')));
  const opened: Session[] = [];
  try {
    await withSchema(async (admin, schema) => {
      await admin.query(SEED);
      const { params, login } = liveParams();
      const conn = await openPg(params, login);
      const tables = (await conn.tables()).filter((t) => t.schema === schema).map((t) => ({ ...t, name: t.remote, design: { ...t.design, name: t.remote } }));
      await conn.close();
      const session = (o: { timeout?: number } = {}, metas?: Record<string, LinkMeta>) => {
        const p: PgParams = { ...params, ...o };
        const fe = join(dir, `front${opened.length}.basecraft`);
        createBaseFile(fe, '0.0.0');
        const db = openBaseFile(fe, 'write', '0.0.0').db;
        addServerLinks(db, 'postgresql', p, tables, metas && tables.map((x) => metas[x.name])); // C7 R11: the wizard's metadata
        db.close();
        const s = Session.open(fe, deps);
        opened.push(s);
        s.setCredential(pgKey(p), login.user, login.password);
        return s;
      };
      try {
        await fn({ admin, schema, tables, session });
      } finally {
        await admin.query('ROLLBACK').catch(() => {}); // a test's lock, if it failed holding one
        for (const s of opened.splice(0)) await s.close();
      }
    });
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}
/** BaseCraft's statements on this schema now running (other test files may run their own at the same time). */
async function activeOn(admin: Client, schema: string): Promise<string> {
  await admin.query('SELECT pg_stat_clear_snapshot()'); // inside admin's transaction, pg_stat_activity is otherwise read once
  return (await admin.query<{ n: string }>(`SELECT count(*) AS n FROM pg_stat_activity
    WHERE application_name = 'BaseCraft' AND state = 'active' AND query LIKE '%' || $1 || '%'`, [schema])).rows[0]!.n;
}

